class C:
    """The JINX "Aurora Glass" palette — futuristic, clean, Apple-style.

    Deep near-black background with a cold blue cast, translucent-looking
    graphite panels, hairline borders (1px, low contrast) and one luminous
    cyan accent. Status colours are desaturated to sit quietly next to the
    glass surfaces instead of shouting over them. Every value here is plain
    hex so the live re-theme can repaint stylesheets by string replacement.
    """
    BG        = "#04070d"   # window backdrop — near-black with a cold cast
    PANEL     = "#0a1017"   # primary glass surface
    PANEL2    = "#0e151e"   # raised surface (hover / secondary cards)
    BORDER    = "#1c2734"   # hairline border (thin, quiet)
    BORDER_B  = "#33475c"   # hairline border, lit (hover / focus)
    BORDER_A  = "#253546"   # hairline border, mid
    PRI       = "#3ee0ff"   # the single luminous accent
    PRI_DIM   = "#1d7f99"   # accent at rest (borders, secondary glyphs)
    PRI_GHO   = "#0c2230"   # accent ghost fill (selected backgrounds)
    ACC       = "#ffb45e"   # warm highlight — amber, no longer neon orange
    ACC2      = "#ffd98a"   # soft gold
    GREEN     = "#4ade80"   # OK / on (Apple-system green, softened)
    GREEN_D   = "#2b8f5b"   # OK border
    RED       = "#ff5f56"   # error (macOS traffic-light red)
    MUTED_C   = "#ff6b81"   # interruption / cancel
    TEXT      = "#cfe9f4"   # body text
    TEXT_DIM  = "#54707f"   # tertiary text
    TEXT_MED  = "#8aa8b8"   # secondary text
    WHITE     = "#f2fbff"   # headings, maximum legibility
    DARK      = "#070c13"   # wells behind inputs and bars
    BAR_BG    = "#0b1219"   # status/toolbars


# Keys tied to the accent colour — status colours (ACC, GREEN, RED…) stay fixed
_HUE_LINKED = (
    "BG", "PANEL", "PANEL2", "BORDER", "BORDER_B", "BORDER_A",
    "PRI", "PRI_DIM", "PRI_GHO", "TEXT", "TEXT_DIM", "TEXT_MED",
    "WHITE", "DARK", "BAR_BG",
)
_PALETTE_DEFAULTS: dict[str, str] = {k: getattr(C, k) for k in _HUE_LINKED}

DEFAULT_UI_COLOR = _PALETTE_DEFAULTS["PRI"]
_ACTIVE_UI_COLOR = DEFAULT_UI_COLOR


def current_ui_color() -> str:
    """Return the active accent, including a live preview not yet persisted."""
    return _ACTIVE_UI_COLOR


def apply_ui_accent(accent_hex: str) -> bool:
    """
    Re-derives the whole teal-family palette from the chosen accent colour
    (hue shift — brightness/saturation ratios are preserved, design stays intact).
    Painted elements (HUD, waveform, metrics) pick up the new colour on the next
    frame; stylesheet-based panels pick it up when they are rebuilt.
    """
    import colorsys
    global _ACTIVE_UI_COLOR

    accent_hex = (accent_hex or "").strip().lower()
    if not (accent_hex.startswith("#") and len(accent_hex) == 7):
        return False
    try:
        int(accent_hex[1:], 16)
    except ValueError:
        return False
    _ACTIVE_UI_COLOR = accent_hex

    def _hsv(h: str) -> tuple[float, float, float]:
        r = int(h[1:3], 16) / 255
        g = int(h[3:5], 16) / 255
        b = int(h[5:7], 16) / 255
        return colorsys.rgb_to_hsv(r, g, b)

    base_h            = _hsv(_PALETTE_DEFAULTS["PRI"])[0]
    acc_h, acc_s, _av = _hsv(accent_hex)
    dh   = acc_h - base_h
    grey = acc_s < 0.08   # near-grey accent → the whole theme is desaturated

    for key, hex0 in _PALETTE_DEFAULTS.items():
        h, s, v = _hsv(hex0)
        if grey:
            s *= 0.15
        r, g, b = colorsys.hsv_to_rgb((h + dh) % 1.0, s, v)
        setattr(C, key, "#{:02x}{:02x}{:02x}".format(
            int(r * 255 + 0.5), int(g * 255 + 0.5), int(b * 255 + 0.5)))
    return True


def current_palette() -> dict[str, str]:
    """A snapshot of the accent-linked colours currently on class C."""
    return {k: getattr(C, k) for k in _HUE_LINKED}


def retheme_all_widgets(old: dict[str, str], new: dict[str, str]) -> None:
    """
    LIVE full theme change. Replaces the old palette colours with the new ones
    in EVERY widget's stylesheet across the app and repaints them. This way the
    colour change applies INSTANTLY across the whole interface — panels, buttons,
    borders included — not just the painted elements. No restart needed.
    """
    mapping = {old[k].lower(): new[k].lower()
               for k in old if old[k].lower() != new.get(k, old[k]).lower()}
    if not mapping:
        return
    app = QApplication.instance()
    if app is None:
        return
    for w in app.allWidgets():
        try:
            if w.window().objectName() == "SettingsCentral":
                continue
            ss = w.styleSheet()
            if ss:
                s2 = ss
                for o, n in mapping.items():
                    if o in s2:
                        s2 = s2.replace(o, n)
                if s2 != ss:
                    w.setStyleSheet(s2)
            w.update()
        except Exception:
            pass


def qcol(h: str, a: int = 255) -> QColor:
    c = QColor(h); c.setAlpha(a); return c

